export function isAllowedAiHost(hostname: string): boolean {
  const h = hostname.trim().toLowerCase().replace(/^www\./, "");
  if (!h) return false;
  return AI_SITE_HOSTS.some(
    (allowed) => h === allowed || h.endsWith(`.${allowed}`),
  );
}
